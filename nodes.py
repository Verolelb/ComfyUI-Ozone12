# Control priority within a band chain, so the 48-widget cap keeps the most
# useful/audible controls (enable, frequency, gain...) instead of filling up
# with attack/release/auto settings.
_PARAM_KIND_PRIORITY = {
    "enable": 0,
    "frequency": 1,
    "gain": 2,
    "threshold": 3,
    "q": 4,
    "shape": 5,
    "phase": 6,
    "offset": 7,
    "attack": 8,
    "release": 9,
    "auto": 10,
    "mix": 11,
    "amount": 12,
}


def _param_kind_rank(name: str) -> int:
    for kind, prio in _PARAM_KIND_PRIORITY.items():
        if kind in name:
            return prio
    return 99


def _filter_widget_params(metas: list[dict]) -> list[dict]:
    """Pick the params that become node widgets (max MAX_WIDGETS).

    Ozone exposes each band chain twice (stereo_main + aux) and many gain
    knobs twice (locked/unlocked). We drop the locked duplicates and then
    prioritize: global gains first, then the audible stereo_main chain (and
    any non-aux param), and the aux chain last. Within a chain the most
    audible controls (enable, frequency, gain, threshold, Q...) come before
    attack/release/auto. Plain alphabetical selection would pick the aux
    chain and fill the cap with attack/auto params, hiding the controls that
    actually drive the sound.
    """
    picked = [m for m in metas if not m.get("locked_dup")]

    def rank(m: dict) -> tuple:
        name = m["name"]
        if name.startswith("gain_") or name == "global_bypass":
            return (0, 0, 0, name)
        if "_aux_" not in name:
            return (1, 0, _param_kind_rank(name), name)
        return (2, 0, _param_kind_rank(name), name)

    picked.sort(key=rank)
    return picked[:MAX_WIDGETS]


def _changed_widget_params(specs: list[dict], widgets: dict) -> dict:
    """Keep only the widget values the user actually changed.

    The engine applies a preset first, then the widget params. Sending every
    widget value (including untouched defaults) would silently reset the
    preset's settings back to the defaults. So we drop values that still
    equal their cached default: the preset keeps its effect, and explicit
    slider/toggle changes still override it.
    """
    params = {}
    for m in specs:
        name = m["name"]
        if name not in widgets:
            continue
        default = m.get("default")
        value = widgets[name]
        try:
            if m.get("bool"):
                unchanged = bool(value) == bool(default)
            elif m.get("choice"):
                unchanged = str(value) == str(default)
            else:
                unchanged = float(value) == float(default)
        except (TypeError, ValueError):
            unchanged = False
        if not unchanged:
            params[name] = value
    return params


def _make_module_node(plugin_filename: str, metas: list[dict]):
    """Create a ComfyUI node class exposing the module's parameters as widgets."""
    params = _filter_widget_params(metas)

    class OzoneModuleNode(IO.ComfyNode):
        PLUGIN_FILE = plugin_filename
        PARAM_SPECS = params

        @classmethod
        def define_schema(cls):
            inputs = [IO.Audio.Input("audio", tooltip="Audio to process.")]
            for m in cls.PARAM_SPECS:
                label = _prettify(m["name"])
                unit = m.get("unit") or ""
                if m["bool"]:
                    inputs.append(
                        IO.Boolean.Input(
                            m["name"],
                            display_name=label,
                            default=bool(m.get("default", False)),
                            tooltip=f"{label} (on/off)",
                        )
                    )
                elif m.get("choice"):
                    choices = list(m.get("choices") or [])
                    default = m.get("default")
                    if default not in choices:
                        default = choices[0] if choices else ""
                    inputs.append(
                        IO.Combo.Input(
                            m["name"],
                            display_name=label,
                            options=choices,
                            default=default,
                            tooltip=f"{label} (choice)",
                        )
                    )
                else:
                    # Only pass finite, well-ordered ranges: non-finite values
                    # would produce invalid JSON for the frontend, and min >= max
                    # breaks the slider.
                    kwargs = {"default": 0.0}
                    if _finite(m.get("default")):
                        kwargs["default"] = float(m["default"])
                    if (
                        _finite(m.get("min"))
                        and _finite(m.get("max"))
                        and m["max"] > m["min"]
                    ):
                        kwargs["min"] = float(m["min"])
                        kwargs["max"] = float(m["max"])
                    if _finite(m.get("step")) and m["step"] > 0:
                        kwargs["step"] = float(m["step"])
                    if "min" in kwargs and "max" in kwargs:
                        kwargs["default"] = max(
                            kwargs["min"], min(kwargs["max"], kwargs["default"])
                        )
                    inputs.append(
                        IO.Float.Input(
                            m["name"],
                            display_name=label,
                            tooltip=f"{label} [{unit}]" if unit else label,
                            **kwargs,
                        )
                    )
            presets = [p["name"] for p in discover_presets(cls.PLUGIN_FILE)]
            inputs.append(
                IO.Combo.Input(
                    "preset",
                    options=[""] + presets,
                    default="",
                    tooltip=(
                        "Ozone preset to apply (factory and user presets found on "
                        "this machine). Values are applied best-effort; unmappable "
                        "parameters are reported in the info output. Needs 'Preset On' "
                        "to take over."
                    ),
                )
            )
            inputs.append(
                IO.Boolean.Input(
                    "preset_enabled",
                    display_name="Preset On",
                    default=False,
                    tooltip=(
                        "ON: the selected preset takes over (manual settings are "
                        "ignored). OFF: manual settings apply and the preset is "
                        "ignored."
                    ),
                )
            )
            inputs.append(
                IO.String.Input(
                    "preset_path",
                    default="",
                    advanced=True,
                    tooltip="Optional path to a raw VST3 state file (.vstpreset) or iZotope .xml preset.",
                )
            )
            inputs.append(
                IO.String.Input(
                    "vst_dir",
                    default=DEFAULT_VST_DIR,
                    advanced=True,
                    tooltip="Folder containing the .vst3 files.",
                )
            )
            module_label = plugin_filename.replace(".vst3", "").replace("Ozone 12 ", "")
            note = _MODULE_NOTES.get(plugin_filename, "")
            description = (
                f"Applies the {plugin_filename} Ozone module with real parameter "
                "widgets (sliders and toggles)."
            )
            if note:
                description += f" {note}"
            return IO.Schema(
                node_id=cls.NODE_ID,
                display_name=f"Ozone 12 {module_label}",
                category="audio/vst/ozone",
                description=description,
                inputs=inputs,
                outputs=[
                    IO.Audio.Output("audio", tooltip="Processed audio."),
                    IO.String.Output("info", tooltip="JSON summary of the processing run."),
                ],
            )

        @classmethod
        def execute(
            cls, audio, preset, preset_path, vst_dir, preset_enabled=False, **widgets
        ) -> IO.NodeOutput:
            if audio is None:
                raise ValueError(f"{cls.NODE_ID}: input audio is None")
            preset_file = None
            if preset:
                for p in discover_presets(cls.PLUGIN_FILE):
                    if p["name"] == preset:
                        preset_file = p["path"]
                        break
            preset_file = preset_file or preset_path or None
            params = _changed_widget_params(cls.PARAM_SPECS, widgets)
            if preset_enabled:
                if preset_file:
                    # Preset takes over: manual settings are ignored.
                    params = {}
                # else: preset requested but none selected -> manual fallback.
            else:
                # Manual mode: the preset is ignored entirely.
                preset_file = None
            waveform = audio["waveform"].float().cpu()
            sample_rate = int(audio["sample_rate"])
            outputs = []
            infos = []
            for i in range(waveform.shape[0]):
                y, info = engine_process(
                    waveform[i].numpy(),
                    sample_rate,
                    cls.PLUGIN_FILE,
                    vst_dir=vst_dir,
                    preset_path=preset_file,
                    params=params,
                )
                outputs.append(torch.from_numpy(y))
                infos.append(info)
            summary = {
                "plugin": cls.PLUGIN_FILE,
                "sample_rate": sample_rate,
                "runs": infos,
                "warnings": [w for info in infos for w in info["warnings"]],
            }
            return IO.NodeOutput(
                {"waveform": torch.stack(outputs, dim=0), "sample_rate": sample_rate},
                json.dumps(summary, default=_json_safe, indent=1),
            )

    key = (
        plugin_filename.replace("Ozone 12 ", "")
        .replace(".vst3", "")
        .replace(" ", "")
        .replace("-", "")
    )
    OzoneModuleNode.NODE_ID = f"OzoneVST{key}"
    OzoneModuleNode.__name__ = f"OzoneVST{key}"
    return OzoneModuleNode


def _build_module_nodes() -> list[type[IO.ComfyNode]]:
    nodes = []
    for filename, metas in _load_param_cache().items():
        try:
            nodes.append(_make_module_node(filename, metas))
        except Exception as e:  # noqa: BLE001 - one bad module shouldn't kill startup
            print(f"[ComfyUI-Ozone12] failed to build node for {filename}: {e}")
    return nodes


