def _default_plugin(plugins: list[str]) -> str:
    return "Ozone 12.vst3" if "Ozone 12.vst3" in plugins else plugins[0]


def _parse_params(params_json: str) -> tuple[dict, list[str]]:
    try:
        data = json.loads(params_json or "{}")
    except json.JSONDecodeError as e:
        return {}, [f"params_json is not valid JSON, ignored: {e}"]
    if not isinstance(data, dict):
        return {}, ["params_json must be a JSON object, ignored"]
    return data, []


def _json_safe(value):
    """Make values JSON-serializable (numpy scalars, etc.)."""
    if isinstance(value, np.generic):
        return value.item()
    return value


def _json_safe_value(value):
    """Recursively coerce a parameter value into a JSON-serializable form.

    Some plugin parameters expose non-scalar objects; fall back to str().
    """
    if value is None or isinstance(value, (bool, int, float, str)):
        return value
    if isinstance(value, np.generic):
        return value.item()
    try:
        if isinstance(value, (list, tuple)):
            return [_json_safe_value(v) for v in value]
        if isinstance(value, dict):
            return {k: _json_safe_value(v) for k, v in value.items()}
        return str(value)
    except Exception:  # noqa: BLE001 - never fail node execution over a value
        return str(value)


