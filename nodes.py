def _save_temp_wav(audio: dict, prefix: str) -> dict:
    """Write the audio to a temp WAV file for the frontend player.

    Returns the ComfyUI file reference {filename, subfolder, type}.
    """
    import folder_paths

    waveform = audio["waveform"].float().cpu().numpy()  # [B, C, S]
    sr = int(audio["sample_rate"])
    wav = waveform[0]
    if wav.ndim != 2:
        wav = wav.reshape(1, -1)
    channels = wav.shape[0]
    samples = np.clip(np.round(wav * 32767.0), -32768, 32767).astype(np.int16)
    interleaved = samples.T.reshape(-1) if channels > 1 else samples[0]
    temp_dir = folder_paths.get_temp_directory()
    os.makedirs(temp_dir, exist_ok=True)
    filename = f"{prefix}_{uuid.uuid4().hex[:8]}.wav"
    path = os.path.join(temp_dir, filename)
    with pywave.open(path, "wb") as f:
        f.setnchannels(channels)
        f.setsampwidth(2)
        f.setframerate(sr)
        f.writeframes(interleaved.tobytes())
    return {"filename": filename, "subfolder": "", "type": "temp"}


def _db_fs(value: float) -> float:
    """Linear amplitude -> dBFS, floored."""
    if value <= 1e-9:
        return -120.0
    return 20.0 * math.log10(value)


def _level_color(db: float) -> tuple[int, int, int]:
    """Green / yellow / red depending on the level."""
    if db < -18:
        return (64, 224, 96)
    if db < -6:
        return (240, 224, 64)
    return (240, 80, 80)


def _render_level_meter(wav: np.ndarray, mode: str, bars: int, meter_h: int, sample_rate: int):
    """Render a peak/RMS history meter. Returns (HWC float32 0..1 image, summary str)."""
    channels = min(wav.shape[0], 2)
    left, right, top, bottom = 46, 14, 20, 28
    gap = 28
    bar_w, gap_w = 5, 1
    width = left + bars * (bar_w + gap_w) + right
    height = top + channels * (meter_h + gap) + bottom
    img = Image.new("RGB", (width, height), (26, 28, 32))
    d = ImageDraw.Draw(img)
    try:
        font = ImageFont.load_default(size=13)
    except TypeError:  # older Pillow
        font = ImageFont.load_default()

    show_peak = mode in ("Peak", "Peak & RMS")
    show_rms = mode in ("RMS", "Peak & RMS")

    summaries = []
    for c in range(channels):
        base_y = top + c * (meter_h + gap)
        label = ("L", "R")[c] if channels == 2 else "M"
        d.text((6, base_y + 2), label, fill=(220, 220, 220), font=font)

        # Gridlines + dB labels
        for db in (-60, -48, -36, -24, -12, 0):
            frac = (db + 60.0) / 60.0
            y = base_y + meter_h - frac * meter_h
            d.line([(left, y), (width - right, y)], fill=(52, 56, 62))
            d.text((left - 34, y - 8), f"{db}", fill=(170, 170, 170), font=font)

        chunk = max(1, wav.shape[1] // bars)
        peak_hold = 0.0
        track_peak = 0.0
        track_rms = 0.0
        for i in range(bars):
            seg = wav[c, i * chunk : (i + 1) * chunk]
            rms = float(np.sqrt(np.mean(np.square(seg)))) if seg.size else 0.0
            peak = float(np.max(np.abs(seg))) if seg.size else 0.0
            track_peak = max(track_peak, peak)
            track_rms = max(track_rms, rms)
            peak_hold = max(peak_hold, peak)
            x0 = left + i * (bar_w + gap_w)
            if show_rms:
                frac = max(0.0, min(1.0, (_db_fs(rms) + 60.0) / 60.0))
                bar_h = max(1, int(frac * (meter_h - 6)))
                d.rectangle(
                    [x0, base_y + meter_h - bar_h - 3, x0 + bar_w, base_y + meter_h - 3],
                    fill=_level_color(_db_fs(rms)),
                )
            if show_peak:
                frac = max(0.0, min(1.0, (_db_fs(peak) + 60.0) / 60.0))
                py = base_y + meter_h - int(frac * (meter_h - 6)) - 5
                d.rectangle([x0, py, x0 + bar_w, py + 2], fill=(255, 255, 255))
        # Peak-hold line
        hold_frac = max(0.0, min(1.0, (_db_fs(peak_hold) + 60.0) / 60.0))
        hold_y = base_y + meter_h - hold_frac * meter_h
        d.line([(left, hold_y), (width - right, hold_y)], fill=(255, 130, 130), width=1)

        summaries.append(
            f"{label} | Peak: {_db_fs(track_peak):.1f} dB | RMS: {_db_fs(track_rms):.1f} dB"
        )

    arr = np.asarray(img, dtype=np.float32) / 255.0  # HWC 0..1
    return arr, " | ".join(summaries)


class OzoneLevelMeter(IO.ComfyNode):
    """Renders a peak/RMS level meter of the audio as an image."""

    @classmethod
    def define_schema(cls):
        return IO.Schema(
            node_id="OzoneLevelMeter",
            display_name="Ozone Level Meter",
            category="audio/vst/ozone",
            description=(
                "Renders a level meter (peak/RMS history per channel) of the audio as an "
                "image and passes the audio through unchanged. Wire the image to "
                "Preview Image."
            ),
            inputs=[
                IO.Audio.Input("audio", tooltip="Audio to visualize."),
                IO.Combo.Input(
                    "mode",
                    options=["Peak & RMS", "Peak", "RMS"],
                    default="Peak & RMS",
                    tooltip="Which level to draw.",
                ),
                IO.Int.Input(
                    "bars",
                    default=120,
                    min=16,
                    max=512,
                    tooltip="Number of time chunks (bars) to draw.",
                ),
                IO.Int.Input(
                    "height",
                    default=140,
                    min=60,
                    max=400,
                    advanced=True,
                    tooltip="Height of each channel meter in pixels.",
                ),
            ],
            outputs=[
                IO.Image.Output(
                    "visualization", tooltip="Level meter image. Wire to Preview Image."
                ),
                IO.Audio.Output("audio", tooltip="Input audio passed through unchanged."),
                IO.String.Output("levels", tooltip="Peak/RMS levels per channel in dBFS."),
            ],
        )

    @classmethod
    def execute(cls, audio, mode, bars, height) -> IO.NodeOutput:
        if audio is None:
            raise ValueError("OzoneLevelMeter: input audio is None")
        waveform = audio["waveform"].float().cpu().numpy()  # [B, C, S]
        images = []
        summaries = []
        sample_rate = int(audio["sample_rate"])
        for wav in waveform:
            arr, summary = _render_level_meter(wav, mode, int(bars), int(height), sample_rate)
            images.append(torch.from_numpy(arr))
            summaries.append(summary)
        # Note: ComfyUI's executor expects each ui value to be a *list* of
        # entries (one per execution); a bare dict would be iterated by key.
        ui = {
            "ozone_meter": [
                {
                    "file": _save_temp_wav(audio, "ozone_meter"),
                    "sample_rate": sample_rate,
                    "duration": round(waveform.shape[-1] / sample_rate, 3),
                }
            ]
        }
        return IO.NodeOutput(torch.stack(images, dim=0), audio, "\n".join(summaries), ui=ui)


