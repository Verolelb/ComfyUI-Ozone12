def _finite(value) -> bool:
    """True for finite numbers (JSON-safe; browser JSON.parse rejects NaN/Infinity)."""
    return isinstance(value, (int, float)) and math.isfinite(value)


def _prettify(name: str) -> str:
    """Turn a python param name into a readable label."""
    label = name.replace("_unlocked", "").replace("_", " ").strip().title()
    return label or name


